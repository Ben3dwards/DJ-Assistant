import { z } from "zod";
import { loadSessionState } from "../state/sessionStorage.js";

export const exportSetlistToSpotifyInputSchema = {
    playlistName: z.string().optional(),
};

export const exportSetlistToSpotifyDescription = `
Export the most recently generated setlist to the user's Spotify account.

Use this when the user says:
- yes, add it to Spotify
- export this setlist
- make this a Spotify playlist
- add these tracks to my Spotify

This tool creates a private Spotify playlist by default.
The user must already be logged into Spotify.
A setlist must have been generated first.
`;

export async function exportSetlistToSpotify(input: {playlistName?: string;}) {
    //MCP documentation recommends console.error for server-side logging
    //as console.log writes to stdout which is reserved for the MCP stdio protocol
    console.error("exportSetlistToSpotify called");

    const state = loadSessionState();
    const spotifySession = state.spotifySession;
    const latestSetlist = state.latestSetlist;

    console.error("Spotify session exists:", !!spotifySession);
    console.error("Latest setlist tracks:", latestSetlist?.tracks?.length ?? 0);

    if (!spotifySession) {
        return {
            content: [
                {
                    type: "text" as const,
                    text: "Spotify is not connected. Please use the Spotify login button first.",
                },
            ],
        };
    }

    if (!latestSetlist || !latestSetlist.tracks.length) {
        return {
            content: [
                {
                    type: "text" as const,
                    text: "No setlist has been generated yet. Please generate a setlist first.",
                },
            ],
        };
    }

    const profileResponse = await fetch("https://api.spotify.com/v1/me", {
        headers: {
            Authorization: `Bearer ${spotifySession.accessToken}`,
        },
    });

    if (!profileResponse.ok) {
        return {
            content: [
                {
                    type: "text" as const,
                    text: "Could not get your Spotify profile. Please log in again.",
                },
            ],
        };
    }

    const playlistName =
        input.playlistName ??
        `DJ Assistant Setlist ${new Date().toLocaleDateString("en-GB")}`;

    const playlistResponse = await fetch(
        `https://api.spotify.com/v1/me/playlists`,
        {
            method: "POST",
            headers: {
                Authorization: `Bearer ${spotifySession.accessToken}`,
                "Content-Type": "application/json",
            },
            body: JSON.stringify({
                name: playlistName,
                description: "Generated by MCP DJ Assistant",
                public: false,
            }),
        }
    );

    if (!playlistResponse.ok) {
        console.error("Failed to create playlist:", await playlistResponse.text());

        return {
            content: [
                {
                    type: "text" as const,
                    text: "Could not create the Spotify playlist.",
                },
            ],
        };
    }

    const playlist = await playlistResponse.json();

    console.error("Created Spotify playlist:", {
        id: playlist.id,
        name: playlist.name,
        url: playlist.external_urls.spotify,
    });

    const uris = latestSetlist.tracks.map(
        (track: { spotifyID: string }) => `spotify:track:${track.spotifyID}`
    );

    console.error("Adding tracks to playlist:", {
        playlistId: playlist.id,
        trackCount: uris.length,
    });

    const addTracksResponse = await fetch(
        `https://api.spotify.com/v1/playlists/${playlist.id}/items`,
        {
            method: "POST",
            headers: {
                Authorization: `Bearer ${spotifySession.accessToken}`,
                "Content-Type": "application/json",
            },
            body: JSON.stringify({
                uris,
            }),
        }
    );

    const addTracksData = await addTracksResponse.json();

    console.error("Spotify add tracks response:", addTracksData);

    if (!addTracksResponse.ok) {
        return {
            content: [
                {
                    type: "text" as const,
                    text: `The playlist was created, but the tracks could not be added: ${JSON.stringify(addTracksData)}`,
                },
            ],
        };
    }

    return {
        content: [
            {
                type: "text" as const,
                text: JSON.stringify(
                    {
                        success: true,
                        playlistName,
                        playlistId: playlist.id,
                        playlistUrl: playlist.external_urls.spotify,
                        trackCount: latestSetlist.tracks.length,
                        spotifyAddTracksResponse: addTracksData,
                    },
                    null,
                    2
                ),
            },
        ],
    };
}